"""Allergen composition of every row in the curated catalogue.

`diet/data/catalogue.py` says what a food is worth in macros. This file says what it is
made of, in the only vocabulary the checker accepts (`diet.allergens.ALLERGENS`). The two
are separate on purpose: macros come from USDA measurements, allergens come from a person
who knows the dish.

Why a table and not inference
-----------------------------
Inference reads the name, and a name is not a recipe. `Makdous` is eggplant stuffed with
WALNUTS and says so nowhere; `Baba Ghanoush` is tahini; `Kishk` is fermented bulgur AND
yogurt; `Fattoush` is a salad whose defining ingredient is fried bread. Every one of those
came back "composite/branded — needs a human". This is that human.

An empty tuple is a POSITIVE claim: this food carries none of the 14 major allergens.
A name absent from this table is not "safe", it is `unknown`, and the planner refuses to
serve an unknown food to a client who declared an allergy. That is the intended failure
mode — a missing entry costs variety, a wrong empty tuple costs a hospital visit.

Where a dish is commonly, but not always, finished with an allergen (`Ful Medames` with
tahini, `Shawarma` with a yoghurt marinade, `Kibbeh` with pine nuts), the tag is present.
Over-blocking is recoverable.
"""
